def safe_parse(code):

    log("AST", "PARSING CODE")

    try:

        tree = ast.parse(code)

        log("AST", "PARSE SUCCESS")

        return tree

    except Exception as e:

        log("AST", f"PARSE FAILED: {e}")

        fixed = sanitize_code(code)

        tree = ast.parse(fixed)

        log("AST", "PARSE SUCCESS AFTER SANITIZE")

        return tree


