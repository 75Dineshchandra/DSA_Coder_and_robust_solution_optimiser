# PARSE INPUTS (FIXED)
# =========================
def parse_inputs(input_raw):
    env = {}

    # split ONLY on top-level commas (safe enough for LC-style inputs)
    parts = []
    current = ""
    bracket_level = 0

    for ch in input_raw:
        if ch == ',' and bracket_level == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += ch
            if ch in "[{(":
                bracket_level += 1
            elif ch in "]})":
                bracket_level -= 1

    if current:
        parts.append(current.strip())

    # now execute each assignment separately
    for part in parts:
        if "=" not in part:
            continue
        exec(part, {}, env)

    return list(env.values())

